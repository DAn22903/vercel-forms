CREATE TABLE IF NOT EXISTS solicitudes_empleo (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  nombre_completo VARCHAR(150) NOT NULL,
  correo_electronico VARCHAR(254) NOT NULL,
  telefono VARCHAR(30) NOT NULL,
  direccion VARCHAR(255) NOT NULL,
  fecha_nacimiento DATE NOT NULL,
  curp_rfc_dni VARCHAR(30) NOT NULL,
  estado_civil VARCHAR(30) NOT NULL,
  puesto_solicitado VARCHAR(150) NOT NULL,
  sueldo_deseado DECIMAL(12, 2) NULL,
  disponibilidad_horario VARCHAR(100) NOT NULL,
  nivel_estudios VARCHAR(100) NOT NULL,
  institucion_educativa VARCHAR(180) NOT NULL,
  estado_estudios ENUM('concluido', 'en_curso') NOT NULL,
  empresa_anterior VARCHAR(180) NOT NULL,
  puesto_anterior VARCHAR(150) NOT NULL,
  tiempo_trabajado VARCHAR(100) NOT NULL,
  motivo_salida VARCHAR(255) NOT NULL,
  telefono_contacto_laboral VARCHAR(30) NOT NULL,
  nombre_referencia VARCHAR(150) NOT NULL,
  telefono_referencia VARCHAR(30) NOT NULL,
  relacion_referencia VARCHAR(100) NOT NULL,
  fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_solicitudes_nombre (nombre_completo),
  KEY idx_solicitudes_puesto (puesto_solicitado),
  KEY idx_solicitudes_fecha (fecha_registro)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
